// Generates an idempotent SQL sync file for the live Supabase project from the
// verified repository in lib/legal-sources.ts (the source of truth).
//
// Run: npx tsx scripts/generate-dataset-sql.ts
// Then paste supabase/sql/sync-dataset-2026-10-20.sql into the Supabase SQL
// editor (dashboard → SQL Editor) and run it. The script is upsert-only: it
// never deletes rows and never rolls back version/last_checked_at history.

import { mkdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { LEGAL_PROVISIONS, LEGAL_SOURCES } from "@/lib/legal-sources"

function q(value: string | null | undefined): string {
  if (value === null || value === undefined) return "null"
  return `'${value.replace(/'/g, "''")}'`
}

function arr(values: string[]): string {
  if (values.length === 0) return "array[]::text[]"
  return `array[${values.map((v) => q(v)).join(",")}]`
}

const sourceRows = LEGAL_SOURCES.map(
  (s) =>
    `  (${q(s.id)}, ${q(s.title)}, ${q(s.citation)}, ${q(s.jurisdiction)}, ` +
    `${q(s.publisher)}, ${q(s.publicationDetails)}, ${q(s.effectiveDate)}, ` +
    `${q(s.sourceUrl)}, ${q(s.licenseNote)}, ${q(s.verificationStatus)}, ` +
    `${s.version}, ${q(s.lastCheckedAt)}, ${q(s.retrievedAt)})`
).join(",\n")

const provisionRows = LEGAL_PROVISIONS.map(
  (p) =>
    `  (${q(p.id)}, ${q(p.sourceId)}, ${q(p.articleOrSection)}, ${q(p.heading)}, ` +
    `${q(p.summary)}, ${q(p.contextNote)}, ${arr(p.keywords)}, ${arr(p.docTypes)}, ` +
    `${q(p.verificationStatus)}, ${q(p.sourceUrl)}, ${q(p.retrievedAt)})`
).join(",\n")

const sql = `-- HAKI AI — dataset sync (generated ${new Date().toISOString().slice(0, 10)})
-- Source of truth: lib/legal-sources.ts. Upsert-only; safe to re-run.
-- Generated by scripts/generate-dataset-sql.ts — do not edit by hand.

begin;

insert into public.legal_sources
  (id, title, citation, jurisdiction, publisher, publication_details, effective_date, source_url, license_note, verification_status, version, last_checked_at, retrieved_at)
values
${sourceRows}
on conflict (id) do update set
  title = excluded.title,
  citation = excluded.citation,
  jurisdiction = excluded.jurisdiction,
  publisher = excluded.publisher,
  publication_details = excluded.publication_details,
  effective_date = excluded.effective_date,
  source_url = excluded.source_url,
  license_note = excluded.license_note,
  verification_status = excluded.verification_status;

insert into public.legal_provisions
  (id, source_id, article_or_section, heading, summary, context_note, keywords, doc_types, verification_status, source_url, retrieved_at)
values
${provisionRows}
on conflict (id) do update set
  source_id = excluded.source_id,
  article_or_section = excluded.article_or_section,
  heading = excluded.heading,
  summary = excluded.summary,
  context_note = excluded.context_note,
  keywords = excluded.keywords,
  doc_types = excluded.doc_types,
  verification_status = excluded.verification_status,
  source_url = excluded.source_url;

commit;
`

const outDir = join(process.cwd(), "supabase", "sql")
mkdirSync(outDir, { recursive: true })
const outFile = join(outDir, "sync-dataset-2026-10-20.sql")
writeFileSync(outFile, sql, "utf8")
console.log(
  `Wrote ${outFile} (${LEGAL_SOURCES.length} sources, ${LEGAL_PROVISIONS.length} provisions)`
)
